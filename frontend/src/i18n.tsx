export type Lang = 'zh' | 'en'

const dictionaries: Record<Lang, Record<MessageKey, string>> = { zh, en }

export const LANGUAGES: { value: Lang; label: string }[] = [
  { value: 'zh', label: '中文' },
  { value: 'en', label: 'English' },
]

const LANG_KEY = 'threedgs.lang'

function loadLang(): Lang {
  const stored = localStorage.getItem(LANG_KEY)
  return stored === 'en' ? 'en' : 'zh'
}

interface I18nValue {
  lang: Lang
  setLang: (lang: Lang) => void
  t: (key: MessageKey, params?: Record<string, string | number>) => string
}

const I18nContext = createContext<I18nValue | null>(null)

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(loadLang)

  // Sync on first paint too, otherwise a reload resets the api layer's language
  useEffect(() => {
    setApiLanguage(lang)
    document.documentElement.lang = lang === 'en' ? 'en' : 'zh-CN'
  }, [lang])

  const setLang = useCallback((next: Lang) => {
    localStorage.setItem(LANG_KEY, next)
    setLangState(next)
    document.documentElement.lang = next === 'en' ? 'en' : 'zh-CN'
    // Let the api layer build error messages in the current language
    setApiLanguage(next)
  }, [])

  const t = useCallback(
    (key: MessageKey, params?: Record<string, string | number>) => {
      const text = dictionaries[lang][key] ?? zh[key] ?? key
      if (!params) return text
      return Object.entries(params).reduce(
        (acc, [name, value]) => acc.replaceAll(`{${name}}`, String(value)),
        text,
      )
    },
    [lang],
  )

  const value = useMemo(() => ({ lang, setLang, t }), [lang, setLang, t])
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n(): I18nValue {
  const value = useContext(I18nContext)
  if (!value) throw new Error('useI18n must be used inside I18nProvider')
  return value
}

/** Map a backend issue.code to a localized label, falling back to its message. */
export function issueLabel(code: string, fallback: string, t: I18nValue['t']): string {
  const key = `issue.${code}` as MessageKey
  return key in zh ? t(key) : fallback
}
